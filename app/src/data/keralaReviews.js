/**
 * Deterministically generates reviews, statistics, and distribution based on product ID
 */
export function getProductAppraisals(productId = "default") {
  // Simple deterministic hash based on string characters
  let hash = 0;
  for (let i = 0; i < productId.length; i++) {
    hash = (hash << 5) - hash + productId.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);

  // Pick 4 distinct reviews based on hash offset
  const count = KERALA_REVIEWS_POOL.length;
  const startIndex = positiveHash % count;
  const selectedReviews = [];
  for (let i = 0; i < 4; i++) {
    const idx = (startIndex + i * 7) % count;
    selectedReviews.push(KERALA_REVIEWS_POOL[idx]);
  }

  // Calculate dynamic stats
  const totalEvaluations = 34 + (positiveHash % 32); // Between 34 and 65 evaluations
  const fiveStarPct = 89 + (positiveHash % 8); // Between 89% and 96%
  const fourStarPct = 100 - fiveStarPct; // Balance
  const score = (4.8 + (positiveHash % 3) * 0.1).toFixed(1); // 4.8, 4.9, or 5.0

  return {
    score,
    totalEvaluations,
    fiveStarPct,
    fourStarPct,
    reviews: selectedReviews,
  };
}
